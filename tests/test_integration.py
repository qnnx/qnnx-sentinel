def test_kem_encapsulation_decapsulation_match(client: TestClient):
    """✓ KEM shared secrets match."""
    headers = get_simple_headers()

    # Generate KEM Keys
    keygen_res = client.post(f"{API_PREFIX}/keygen", json={"algorithm": "ML-KEM-768", "key_type": "kem"}, headers=headers)
    assert keygen_res.status_code == 200
    keys = keygen_res.json()
    
    # Encapsulate
    encap_res = client.post(f"{API_PREFIX}/kem/encapsulate", json={"algorithm": "ML-KEM-768", "public_key": keys["public_key"]}, headers=headers)
    assert encap_res.status_code == 200
    encap_data = encap_res.json()
    
    # Decapsulate
    decap_res = client.post(
        f"{API_PREFIX}/kem/decapsulate",
        json={
            "algorithm": "ML-KEM-768", 
            "private_key": keys["private_key"],
            "ciphertext": encap_data["ciphertext"]
        },
        headers=headers
    )
    assert decap_res.status_code == 200
    decap_data = decap_res.json()
    
    # Verify Match
    assert encap_data["shared_secret"] == decap_data["shared_secret"], "CRITICAL: KEM Shared Secrets do NOT match!"

def test_dsa_sign_and_verify_flow(client: TestClient):
    """✓ Valid signatures verify successfully. ✓ Tampered messages fail verification."""
    headers = get_simple_headers()
    message = "This is a highly classified document."
    message_b64 = base64.b64encode(message.encode()).decode()

    # Generate DSA Keys
    keygen_res = client.post(f"{API_PREFIX}/keygen", json={"algorithm": "ML-DSA-65", "key_type": "dsa"}, headers=headers)
    assert keygen_res.status_code == 200
    keys = keygen_res.json()

    # Sign the message
    sign_res = client.post(
        f"{API_PREFIX}/sign",
        json={
            "algorithm": "ML-DSA-65", 
            "private_key": keys["private_key"],
            "message": message_b64
        },
        headers=headers
    )
    assert sign_res.status_code == 200
    signature = sign_res.json()["signature"]

    # Verify the valid signature
    verify_res = client.post(
        f"{API_PREFIX}/verify",
        json={
            "algorithm": "ML-DSA-65", 
            "public_key": keys["public_key"],
            "message": message_b64,
            "signature": signature
        },
        headers=headers
    )

    assert verify_res.status_code == 200
    print(f"\n!!! VERIFY RESPONSE: {verify_res.json()}")
    assert verify_res.json()["is_valid"] is True, "Valid signature was incorrectly rejected!"

    # Tamper with the message and verify it fails
    tampered_message = "This is a highly classified document!"
    tampered_b64 = base64.b64encode(tampered_message.encode()).decode()
    
    tamper_res = client.post(
        f"{API_PREFIX}/verify",
        json={
            "algorithm": "ML-DSA-65", 
            "public_key": keys["public_key"],
            "message": tampered_b64,
            "signature": signature
        },
        headers=headers
    )
    if tamper_res.status_code == 200:
        assert tamper_res.json()["is_valid"] is False, "Tampered message was incorrectly validated!"
    else:
        assert tamper_res.status_code in [400, 422], "Tampered message should trigger a validation failure or False."


